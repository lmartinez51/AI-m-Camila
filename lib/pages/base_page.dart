  /// @brief Cleans orphaned listeners, cuts off streaming hooks, and completely unlocks global wakelocks natively hooked into the Android/iOS subsystem.
  @override
  void dispose() {
    // Eliminar listeners para evitar llamadas después de dispose
    _welcomeMessageTimer?.cancel();
    routeObserver.unsubscribe(this);
    audioStreamProvider.onAudioProcessed = null;
    // Le devolvemos el control de energía al celular al salir de la plática
    WakelockPlus.disable();
    super.dispose();
  }
