/// @brief Abstract base presentation layer for main app pages containing avatar and chat functionality.
abstract class BasePage extends StatefulWidget {
  final String? videoAsset;
  final String pageType;

  /// @brief Core constructor for the base page.
  /// @param key The widget key identifier.
  /// @param videoAsset The optional initial video asset to play in the background.
  /// @param pageType String identifying the specific derived page mode.
  const BasePage({super.key, this.videoAsset, required this.pageType});

  @override
  State<BasePage> createState() => _BasePageState();
}

/// @brief State controller for the BasePage, managing audio/video streams, timers, and permissions.
class _BasePageState extends State<BasePage> with RouteAware {
  Model? _model;
  bool isRecording = false;
  bool permissionsGranted = false;
  bool showWelcomeMessage = false;
  bool isProcessing =
      false; // NUEVO: Estado para saber si la IA está "pensando"

  Timer? _welcomeMessageTimer;
  bool isVideoEnabled = false;
  bool isPhoneActive = false;
  String? _videoUrl;

  late DidService didService;
  late VideoProvider videoProvider;
  late AudioStreamProvider audioStreamProvider;
  late UserProvider userProvider;

  /// @brief Initializes page providers, services, and wakes the lock for continuous operation.
  @override
  void initState() {
    super.initState();
    _model = Provider.of<Model>(context, listen: false);
    didService = DidService();
    WidgetsBinding.instance.addPostFrameCallback((_) {
      checkAndRequestPermissions();
    });
    audioStreamProvider =
        Provider.of<AudioStreamProvider>(context, listen: false);
    userProvider = Provider.of<UserProvider>(context, listen: false);

    // Iniciar el VideoProvider desde un asset o URL
    videoProvider = Provider.of<VideoProvider>(context, listen: false);
    videoProvider.initializeFromAsset(widget.videoAsset!);
    _checkWelcomeMessageStatus();
    _checkWakeWordAutoStart(); // Intercept Wake Word trigger
    audioStreamProvider.onAudioProcessed = () async {
      if (isVideoEnabled) {
        await handleVideoCreation();
      }
    };
    // 2. INICIO: Despertamos a la bestia
    WakelockPlus.enable();
  }

  /// @brief Toggles between audio-only and video avatar rendering modes.
  /// @param value True to enable video mode, false to revert to audio mode.
  /// @return `Future<void>`
  Future<void> _toggleVideo(bool value) async {
    setState(() {
      isVideoEnabled = value;
    });
    if (value) {
      // Ejecutar el proceso completo de creación de video
      debugPrint("Ejecutandose video temporal");
    }
  }

  /// @brief Displays a floating Snackbar message natively styled as an AI system notification.
  /// @param message The text content to display.
  /// @param isError Flag indicating whether the message should be styled as an error (red).
  void _showCamilaMessage(String message, {bool isError = false}) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(
          message,
          style: const TextStyle(
              fontFamily: 'Outfit', color: Colors.white, fontSize: 13),
        ),
        backgroundColor: isError ? Colors.redAccent : const Color(0xFF6C63FF),
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
      ),
    );
  }

  /// @brief Uploads an audio slice to the D-ID API, generates a synchronized avatar talking video, and queues it up for playback.
  /// @param audioFilePath Local path to the WAV file generated by the user or TTS engine.
  /// @return `Future<void>`
  Future<void> _createVideo(String audioFilePath) async {
    setState(() =>
        isProcessing = true); // Indicamos a la UI que Camila está procesando
    try {
      final audioUrl = await didService.uploadAudioToDID(audioFilePath);
      final videoData = await didService.createAvatarVideo(
          'https://create-images-results.d-id.com/auth0%7C63f72eea17540f42f4946035/upl_-tvsRbtIAG4nf0R6bp8xc/image.jpeg',
          audioUrl);

      final talkId = videoData['id'];
      if (talkId == null) throw Exception("Talk ID is null");

      _videoUrl = await didService.getAvatarTalkingVideoWithPolling(talkId);
      if (_videoUrl == null) throw Exception("Video URL is null");

      final tempVideoPath = await videoProvider.saveVideoToTempDir(_videoUrl!);
      if (tempVideoPath.isEmpty) throw Exception("Failed to save video");

      videoProvider.playVideo(tempVideoPath);
    } catch (e) {
      debugPrint('Error during video creation: $e');
      _showCamilaMessage("Ugh, my brain hurts (Server Error). Try again.",
          isError: true);
    } finally {
      if (mounted) setState(() => isProcessing = false); // Ocultar carga
    }
  }

  /// @brief Orchestrates video generation specifically mapped from incoming PCM streams derived from AI responses.
  /// @return `Future<void>`
  Future<void> handleVideoCreation() async {
    try {
      // Convertir el PCM a WAV
      final wavFilePath = await audioStreamProvider.convertPCMToWAV();
      // Usar la función común para crear el video
      await _createVideo(wavFilePath);
    } catch (e) {
      debugPrint('Error durante el proceso de creación de video: $e');
    }
  }

  /// @brief Wrapper delegator for the D-ID generation system natively bypassing PCM conversion gaps.
  /// @param filePath Raw string path pointing precisely to the pre-rendered audio asset.
  /// @return `Future<void>`
  Future<void> handleDidVideoCreation(String filePath) async {
    try {
      // Usar la función común para crear el video
      await _createVideo(filePath);
    } catch (e) {
      debugPrint('Error durante el proceso de creación de video: $e');
    }
  }

  /// @brief Registers this specific route to the RouteObserver layout for tracking visibility lifecycle transitions.
  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    // Suscribirse a RouteObserver
    routeObserver.subscribe(this, ModalRoute.of(context) as PageRoute);
  }

  /// @brief Queries local device SharedPreferences to trigger a one-time welcome overlay when Camila initializes.
  /// @return `Future<void>`
  Future<void> _checkWelcomeMessageStatus() async {
    SharedPreferences prefs = await SharedPreferences.getInstance();
    bool hasShownWelcomeMessage =
        prefs.getBool('hasShownWelcomeMessage') ?? false;

    if (!hasShownWelcomeMessage) {
      // Marcar de inmediato que el mensaje se está mostrando para evitar duplicados
      await prefs.setBool('hasShownWelcomeMessage', true);
      // Mostrar mensaje de bienvenida
      Future.delayed(const Duration(seconds: 2), () {
        if (!mounted) return; // Verifica si el widget sigue en el árbol
        setState(() {
          showWelcomeMessage = true;
        });
        // Ocultar mensaje de bienvenida después de 1 segundos
        _welcomeMessageTimer = Timer(const Duration(seconds: 2), () {
          if (!mounted) return; // Verifica si el widget sigue en el árbol
          setState(() {
            showWelcomeMessage = false;
          });
        });
      });
    }
  }

  /// @brief Checks if the app was launched via wake word and triggers the AI greeting.
  Future<void> _checkWakeWordAutoStart() async {
    SharedPreferences prefs = await SharedPreferences.getInstance();
    bool autoStart = prefs.getBool('autoStartVoice') ?? false;

    if (autoStart) {
      // 1. Apagamos la bandera para que no se cicle
      await prefs.setBool('autoStartVoice', false);

      if (!mounted) return;

      debugPrint("🎤 Wake Word Auto-Trigger: Delegando al Provider...");

      // 2. Llamamos a nuestra nueva función limpia
      final audioStreamProvider =
          Provider.of<AudioStreamProvider>(context, listen: false);
      audioStreamProvider.handleWakeWordGreeting();
    }
  }

  /// @brief Triggers the WebRTC microphone pipeline to capture audio or pauses video components if operating under visual mode.
  /// @return `Future<void>`
  Future<void> startRecording() async {
    if (_model != null && !isRecording) {
      if (isVideoEnabled) {
        // Acceder a VideoProvider y pausar el video actualmente en reproducción
        videoProvider.currentController?.pause();
        // Iniciar la grabación para video
        await audioStreamProvider.startRecordingForVideo();
        setState(() {
          isRecording = true;
        });
      } else {
        // Audio Mode: Just Unmute
        audioStreamProvider.unmuteMicrophone();
      }
    }
  }

  /// @brief Ceases microphone capture, dumps PCM stream to local storage, and fires payload context toward the active AI logic brain.
  /// @return `Future<void>`
  Future<void> stopRecordingAndSend() async {
    if (_model != null) {
      if (isVideoEnabled && isRecording) {
        // Acceder a VideoProvider y continuar el video actualmente en reproducción
        videoProvider.currentController?.play();
        // Detener la grabación y enviar el audio
        final filePath = await audioStreamProvider.stopRecordingForVideo();
        String userName = userProvider.user!.name;
        _model!.addUserMessage(userName, 'Mensaje de audio enviado');
        setState(() {
          isRecording = false;
        });
        String response = await _model!.sendUserAudioInput(context, filePath!);
        _model!.addModelMessage(response);
        final responseAudioPath = audioStreamProvider.audioFilePath;
        handleDidVideoCreation(responseAudioPath!);
      } else {
        // Audio Mode: Just Mute
        audioStreamProvider.muteMicrophone();
      }
    }
  }

  /// @brief Validates native OS microphone permissions, halting action execution if access is completely deprived.
  /// @return `Future<bool>` Returns true if access is gracefully granted, false otherwise.
  Future<bool> checkAndRequestPermissions() async {
    if (_model != null) {
      final status = await Permission.microphone.status;
      if (status.isGranted) {
        setState(() {
          permissionsGranted = true;
        });
        await audioStreamProvider.retryRecording();
        return true;
      } else {
        final microphonePermissionStatus =
            await _model!.requestMicrophonePermission();
        final granted = microphonePermissionStatus.isGranted;
        setState(() {
          permissionsGranted = granted;
        });
        if (granted) {
          await audioStreamProvider.retryRecording();
        }
        return granted;
      }
    }
    return false;
  }

  /// @brief Fallback initiator requesting microphone privileges if initially denied by OS constraints.
  /// @return `Future<void>`
  Future<void> retryPermissions() async {
    if (!permissionsGranted) {
      final granted = await checkAndRequestPermissions();
      if (granted) {
        setState(() {
          permissionsGranted = true;
        });
      }
    }
  }

  // Función para alternar entre grabar y detener
  /// @brief Orchestrates switching native modes connecting microphone feeds or firing payloads depending on current UI toggle constraints.
  void toggleRecording() async {
    if (!permissionsGranted) {
      // Mostrar SnackBar si no hay permisos
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: const Text(
            'Unfortunately, access to the microphone has not been granted.',
            style: TextStyle(
              fontFamily: 'Readex Pro',
              color: Colors.white,
              fontSize: 12,
            ),
          ),
          backgroundColor: const Color(0xFF4B39EF),
          action: SnackBarAction(
            label: 'Retry',
            onPressed: retryPermissions,
          ),
        ),
      );
      return;
    }

    try {
      if (isVideoEnabled) {
        if (isRecording) {
          await stopRecordingAndSend();
        } else {
          await startRecording();
        }
      } else {
        // MODO AUDIO: Aquí controlamos el switch visual basado en el Provider
        if (audioStreamProvider.isMicrophoneMuted) {
          await audioStreamProvider.startRecordingAndUnmute(forceStart: true);
        } else {
          await audioStreamProvider.stopRecordingAndMute();
        }
      }
    } catch (e) {
      debugPrint("El error al iniciar es: $e");
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            'Error switching microphone state: $e',
            style: const TextStyle(
              fontFamily: 'Readex Pro',
              color: Colors.white,
              fontSize: 12,
            ),
          ),
          duration: const Duration(seconds: 2),
          backgroundColor: Colors.red,
        ),
      );
    }
  }

